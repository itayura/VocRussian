const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const packageJson = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
const commit = String(process.env.BUILD_SHA || process.env.GITHUB_SHA || "local").slice(0, 12);
const builtAt = process.env.BUILD_TIMESTAMP || new Date().toISOString();
const output = `// Generated by scripts/write-build-info.js.\nwindow.PRIVYETIK_BUILD = Object.freeze(${JSON.stringify({
  version: packageJson.version,
  commit,
  builtAt
}, null, 2)});\n`;

fs.writeFileSync(path.join(root, "js", "build-info.js"), output, "utf8");
console.log(`Wrote web build ${packageJson.version} (${commit}).`);
